export default function DashboardDoTecnico({
  onLogout,
  onNavigate,
  championshipStarted,
  onToggleChampionship,
}: {
  onLogout?: () => void;
  onNavigate?: (key: string) => void;
  championshipStarted?: boolean;
  onToggleChampionship?: () => void;
}) {
  const [stats, setStats] = useState<any>({
    totalEquipes: 18,
    arenasAtivas: 3,
    validacoesPendentes: 18,
    torneioAtivo: { nome: "Torneio Sumô 2026", status: "CHAVEAMENTO_PRONTO" },
    atividadesRecentes: []
  });

  useEffect(() => {
    fetch("http://localhost:3000/api/v1/adm/dashboard-stats", { credentials: "include" })
      .then((res) => res.json())
      .then((data) => {
        if (data && typeof data.totalEquipes === "number") {
          setStats(data);
        }
      })
      .catch((err) => {
        console.warn("Could not fetch dashboard stats from API:", err);
      });
  }, []);

  return (
    <div className="bg-[#f7f9ff] content-stretch flex flex-col items-start pl-0 md:pl-[256px] relative min-h-screen w-full" data-name="Dashboard do Técnico">
      <TopNavigationBar
        championshipStarted={championshipStarted}
        onToggleChampionship={onToggleChampionship}
        onLogout={onLogout}
      />
      <CanvasContent stats={stats} onNavigate={onNavigate} />
    </div>
  );
}